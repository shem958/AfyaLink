package models

import (
	"time"
)

// Doctor represents a clinician/doctor in the system
type Doctor struct {
	ID             string    `json:"id" gorm:"primaryKey"`
	Name           string    `json:"name" gorm:"not null"`
	Hospital       string    `json:"hospital"`
	Specialization string    `json:"specialization"`
	Email          string    `json:"email" gorm:"uniqueIndex;not null"`
	Phone          string    `json:"phone"`
	PasswordHash   string    `json:"-"`
	Patients       []Patient `json:"patients,omitempty" gorm:"foreignKey:DoctorID"`
	CreatedAt      time.Time `json:"created_at"`
	UpdatedAt      time.Time `json:"updated_at"`
}

// Patient represents a patient enrolled in the monitoring system
type Patient struct {
	ID           string         `json:"id" gorm:"primaryKey"`
	Name         string         `json:"name" gorm:"not null"`
	Age          int            `json:"age"`
	Gender       string         `json:"gender"`
	Phone        string         `json:"phone" gorm:"uniqueIndex;not null"`
	Condition    string         `json:"condition"` // "hypertension", "diabetes", "asthma"
	DoctorID     string         `json:"doctor_id"`
	Doctor       *Doctor        `json:"doctor,omitempty" gorm:"foreignKey:DoctorID"`
	PinHash      string         `json:"-"`
	Readings     []HealthReading `json:"readings,omitempty" gorm:"foreignKey:PatientID"`
	Medications  []Medication   `json:"medications,omitempty" gorm:"foreignKey:PatientID"`
	Alerts       []Alert        `json:"alerts,omitempty" gorm:"foreignKey:PatientID"`
	CreatedAt    time.Time      `json:"created_at"`
	UpdatedAt    time.Time      `json:"updated_at"`
}

// HealthReading stores a single health metric recorded by a patient
type HealthReading struct {
	ID          string    `json:"id" gorm:"primaryKey"`
	PatientID   string    `json:"patient_id" gorm:"index;not null"`
	Patient     *Patient  `json:"patient,omitempty" gorm:"foreignKey:PatientID"`
	Type        string    `json:"type"`        // "blood_pressure", "glucose", "heart_rate", "weight"
	Systolic    *float64  `json:"systolic,omitempty"`   // for BP
	Diastolic   *float64  `json:"diastolic,omitempty"`  // for BP
	Value       *float64  `json:"value,omitempty"`      // for single-value readings
	Unit        string    `json:"unit"`        // "mmHg", "mmol/L", "bpm", "kg"
	Notes       string    `json:"notes"`
	RecordedAt  time.Time `json:"recorded_at"`
	CreatedAt   time.Time `json:"created_at"`
}

// Medication represents a prescribed medication with a schedule
type Medication struct {
	ID          string    `json:"id" gorm:"primaryKey"`
	PatientID   string    `json:"patient_id" gorm:"index;not null"`
	Name        string    `json:"name" gorm:"not null"`
	Dosage      string    `json:"dosage"`
	Schedule    string    `json:"schedule"` // "08:00", "08:00,20:00"
	Frequency   string    `json:"frequency"` // "daily", "twice_daily", "weekly"
	StartDate   time.Time `json:"start_date"`
	EndDate     *time.Time `json:"end_date,omitempty"`
	Active      bool      `json:"active" gorm:"default:true"`
	CreatedAt   time.Time `json:"created_at"`
	UpdatedAt   time.Time `json:"updated_at"`
}

// MedicationLog tracks when a patient marks a medication as taken
type MedicationLog struct {
	ID           string    `json:"id" gorm:"primaryKey"`
	MedicationID string    `json:"medication_id" gorm:"index;not null"`
	PatientID    string    `json:"patient_id" gorm:"index;not null"`
	TakenAt      time.Time `json:"taken_at"`
	CreatedAt    time.Time `json:"created_at"`
}

// Alert represents a risk alert generated by the alert engine
type Alert struct {
	ID           string    `json:"id" gorm:"primaryKey"`
	PatientID    string    `json:"patient_id" gorm:"index;not null"`
	Patient      *Patient  `json:"patient,omitempty" gorm:"foreignKey:PatientID"`
	ReadingID    string    `json:"reading_id"`
	Type         string    `json:"type"`     // "high_bp", "high_glucose", "missed_medication", "symptom"
	Severity     string    `json:"severity"` // "low", "medium", "high", "critical"
	Message      string    `json:"message"`
	Acknowledged bool      `json:"acknowledged" gorm:"default:false"`
	CreatedAt    time.Time `json:"created_at"`
	UpdatedAt    time.Time `json:"updated_at"`
}

// Symptom represents a patient-reported symptom
type Symptom struct {
	ID          string    `json:"id" gorm:"primaryKey"`
	PatientID   string    `json:"patient_id" gorm:"index;not null"`
	Symptoms    string    `json:"symptoms"` // JSON array of symptom names
	Notes       string    `json:"notes"`
	Severity    string    `json:"severity"` // "mild", "moderate", "severe"
	ReportedAt  time.Time `json:"reported_at"`
	CreatedAt   time.Time `json:"created_at"`
}

// Message represents a message exchanged between doctor and patient
type Message struct {
	ID         string    `json:"id" gorm:"primaryKey"`
	PatientID  string    `json:"patient_id" gorm:"index;not null"`
	DoctorID   string    `json:"doctor_id" gorm:"index;not null"`
	SenderType string    `json:"sender_type"` // "doctor" or "patient"
	Content    string    `json:"content" gorm:"not null"`
	Read       bool      `json:"read" gorm:"default:false"`
	SentAt     time.Time `json:"sent_at"`
	CreatedAt  time.Time `json:"created_at"`
}

// Notification tracks sent notifications
type Notification struct {
	ID         string    `json:"id" gorm:"primaryKey"`
	RecipientID string   `json:"recipient_id"`
	RecipientType string `json:"recipient_type"` // "patient" or "doctor"
	Channel    string    `json:"channel"` // "sms", "push", "email"
	Message    string    `json:"message"`
	Status     string    `json:"status"` // "sent", "pending", "failed"
	CreatedAt  time.Time `json:"created_at"`
}
